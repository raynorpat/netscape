#!/usr/bin/env python3
"""Render the auditable Windows 3.02 menu transcription, or verify resources.

Only metadata from the historical executable is needed. --check requires no
vendor binary or Windows compiler. --compare reads the native menu dump produced
by the frontend: mode<TAB>depth<TAB>id<TAB>flags<TAB>label, preserving label tabs.
"""
import argparse
import json
from pathlib import Path
import re
import sys


ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / "cmake/tests/fixtures/windows302-menus.json"
GENERATED = ("browser", "mail", "news")


def load_manifest(path=FIXTURE):
    return json.loads(Path(path).read_text(encoding="utf-8"))


def expanded_items(manifest, name):
    """Expand runtime menus and declared port extensions, keeping originals intact."""
    def copy_items(items):
        result = []
        for item in items:
            item = dict(item)
            if "items" in item:
                item["items"] = copy_items(manifest["runtime_window_items"] if item["label"] == "&Window" else item["items"])
            result.append(item)
        return result

    result = copy_items(manifest["menus"][name]["items"])
    for extension in manifest.get("native_extensions", []):
        if extension["menu"] != name:
            continue
        parent = result
        for label in extension["parent_path"]:
            matches = [item for item in parent if item["label"] == label and "items" in item]
            if len(matches) != 1:
                raise ValueError("Ambiguous extension parent: " + label)
            parent = matches[0]["items"]
        matches = [index for index, item in enumerate(parent) if item.get("command") == extension["after_command"]]
        if len(matches) != 1:
            raise ValueError("Ambiguous extension anchor: " + extension["after_command"])
        position = matches[0] + 1
        parent[position:position] = copy_items(extension["items"])
    return result


def resource_quote(label):
    return '"' + label.replace('"', '""').replace("\t", "\\t") + '"'


def render_items(items, depth=1):
    lines = []
    pad = " " * depth
    for item in items:
        if "items" in item:
            lines += [pad + "POPUP " + resource_quote(item["label"]), pad + "BEGIN"]
            lines += render_items(item["items"], depth + 1)
            lines.append(pad + "END")
        elif not item["label"]:
            lines.append(pad + "MENUITEM SEPARATOR")
        else:
            command = item["command"]
            if not command:
                raise ValueError("Missing command for " + item["label"])
            flags = ", GRAYED" if item["disabled"] else ""
            lines.append(pad + "MENUITEM " + resource_quote(item["label"]) + ", " + command + flags)
    return lines


def accelerators(name):
    # The historical labels are authoritative; familiar modern aliases may remain.
    rows = [
        ('"N"', "ID_BROWSER_NEW", "CONTROL"),
        ('"M"', "ID_CLIENT_COMPOSE", "CONTROL"),
        ('"S"', "ID_MENU_SAVE_MESSAGE", "CONTROL"),
        ('"H"', "ID_MESSAGE_SEND_QUEUED", "CONTROL"),
        ('"F"', "ID_BROWSER_FIND", "CONTROL"),
        ('"R"', "ID_MESSAGE_REPLY", "CONTROL"),
        ('"L"', "ID_MESSAGE_FORWARD", "CONTROL"),
        ('"A"', "ID_MENU_SELECT_THREAD", "CONTROL, SHIFT"),
        ('"A"', "0xE12A", "CONTROL"),
        ('"C"', "0xE122", "CONTROL"),
        ('"X"', "0xE123", "CONTROL"),
        ('"V"', "0xE125", "CONTROL"),
        ('"Z"', "0xE12B", "CONTROL"),
        ('"E"', "0xE12C", "CONTROL"),
        ('"W"', "0xE141", "CONTROL"),
        ('"B"', "ID_BOOKMARKS_SHOW", "CONTROL"),
        ("VK_F3", "ID_MENU_FIND_AGAIN", ""),
        ("VK_F5", "ID_MESSAGE_GET", ""),
        ("VK_ESCAPE", "ID_NAV_STOP", ""),
        ("VK_LEFT", "ID_MESSAGE_PREVIOUS", "ALT"),
        ("VK_RIGHT", "ID_MESSAGE_NEXT", "ALT"),
    ]
    if name == "mail":
        rows += [
            ('"T"', "ID_MESSAGE_GET", "CONTROL"),
            ('"K"', "ID_MENU_COMPRESS_FOLDER", "CONTROL"),
            ('"R"', "ID_MESSAGE_REPLY_ALL", "CONTROL, SHIFT"),
            ("VK_DELETE", "ID_MESSAGE_DELETE", ""),
        ]
    else:
        # Subscription remains a contextual keyboard action, absent from 3.02's menus.
        rows.append(("VK_SPACE", "ID_NEWS_SUBSCRIBE", ""))
    lines = ["", "IDR_" + name.upper() + "_ACCEL ACCELERATORS", "BEGIN"]
    for key, command, modifiers in rows:
        lines.append(" " + key + ", " + command + ", VIRTKEY" + (", " + modifiers if modifiers else ""))
    return lines + ["END"]


def render_resource(manifest, name):
    menu = manifest["menus"][name]
    lines = [
        "/* Generated by cmake/tools/generate_windows_menus.py.",
        " * Labels/order: cmake/tests/fixtures/windows302-menus.json (3.02 metadata).",
        " * Unsupported facilities remain visible and disabled. Do not edit here.",
        " */",
        menu["resource"] + " MENU",
        "BEGIN",
    ] + render_items(expanded_items(manifest, name)) + ["END"]
    if name in ("mail", "news"):
        lines += accelerators(name)
    return "\n".join(lines) + "\n"


def render_links(manifest):
    lines = [
        "/* Generated by cmake/tools/generate_windows_menus.py.",
        " * Historical RT_STRING routes from windows302-menus.json; availability is unverified.",
        " * Included inside original_help_url. Do not edit here.",
        " */",
        "static const struct { UINT command; const char *url; } original_links[] = {",
    ]
    entries = manifest["link_metadata"]["entries"]
    for entry in entries:
        if entry["command"]:
            lines.append("    { %s, %s }, /* RT_STRING %d */" %
                         (entry["command"], json.dumps(entry["url"]), entry["url_string_id"]))
    # The native directory toolbar retained this software shortcut. Its route is
    # the original Help > Software resource, not a new historical menu entry.
    software = next(entry for entry in entries if entry["command"] == "ID_MENU_HELP_SOFTWARE")
    lines.append("    { ID_DIRECTORY_LAST, %s }, /* Native toolbar alias; RT_STRING %d */" %
                 (json.dumps(software["url"]), software["url_string_id"]))
    return "\n".join(lines + ["};", ""])


def command_values():
    values = {}
    for filename in ("resource.h", "menu_resource.h", "composer_resource.h"):
        source = (ROOT / "cmd/winfe" / filename).read_text(encoding="utf-8")
        for name, expr in re.findall(r"^#define[ \t]+(\w+)[ \t]+([^\r\n]+)", source, re.M):
            try:
                values[name] = int(expr.strip(), 0)
            except ValueError:
                pass
    return values


def resolve_command(command, values):
    if command is None:
        return 0
    parts = command.split("+")
    return sum(values[part.strip()] if part.strip() in values else int(part.strip(), 0) for part in parts)


def expected_rows(manifest, name, values=None):
    values = command_values() if values is None else values
    rows = []

    def walk(items, depth):
        for item in items:
            popup = "items" in item
            rows.append({"depth": depth, "id": -1 if popup else resolve_command(item["command"], values),
                         "label": item["label"], "disabled": item.get("disabled", False)})
            if popup:
                walk(item["items"], depth + 1)

    walk(expanded_items(manifest, name), 0)
    return rows


def compare_native(manifest, path):
    actual = {}
    aliases = {str(value): name for name, value in (("browser", 0), ("mail", 1), ("news", 2), ("composer", 3))}
    aliases.update({"100": "browser", "102": "mail", "106": "news", "103": "composer"})
    for line in Path(path).read_text(encoding="utf-8").splitlines():
        if not line or line.startswith("#"):
            continue
        mode, depth, command, flags, label = line.split("\t", 4)
        mode = aliases.get(mode, mode)
        actual.setdefault(mode, []).append({"depth": int(depth), "id": int(command),
                                             "flags": int(flags, 0), "label": label})
    errors = []
    for name in manifest["menus"]:
        wanted = expected_rows(manifest, name)
        found = actual.get(name, [])
        if len(wanted) != len(found):
            errors.append("%s: expected %d rows, got %d" % (name, len(wanted), len(found)))
        for index, (expected, observed) in enumerate(zip(wanted, found)):
            for field in ("depth", "id", "label"):
                if expected[field] != observed[field]:
                    errors.append("%s[%d] %s: %r != %r" % (name, index, field, observed[field], expected[field]))
            if expected["disabled"] and not (observed["flags"] & 3):
                errors.append("%s[%d] unavailable command is enabled" % (name, index))
    return errors


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail if generated resources are stale")
    parser.add_argument("--dump-expected", action="store_true", help="print expanded numeric trees as JSON")
    parser.add_argument("--compare", type=Path, help="compare a native .menus.tsv dump")
    parser.add_argument("--fixture", type=Path, default=FIXTURE)
    args = parser.parse_args()
    manifest = load_manifest(args.fixture)
    if args.dump_expected:
        print(json.dumps({name: expected_rows(manifest, name) for name in manifest["menus"]}, indent=2))
        return 0
    if args.compare:
        errors = compare_native(manifest, args.compare)
        for error in errors:
            print(error, file=sys.stderr)
        return bool(errors)
    stale = []
    outputs = {manifest["menus"][name]["file"]: render_resource(manifest, name) for name in GENERATED}
    outputs["cmd/winfe/res/original-links.inc"] = render_links(manifest)
    for filename, wanted in outputs.items():
        path = ROOT / filename
        if args.check:
            if not path.exists() or path.read_text(encoding="utf-8") != wanted:
                stale.append(str(path.relative_to(ROOT)))
        else:
            path.write_text(wanted, encoding="ascii")
    if stale:
        print("Stale Windows 3.02 menu resources: " + ", ".join(stale), file=sys.stderr)
        return 1
    print("Windows 3.02 menu resources match fixture." if args.check else "Generated Windows 3.02 menu resources.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
