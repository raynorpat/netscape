std::string hex(const std::string &s)
{
    static const char digits[]="0123456789abcdef";
    std::string result;
    for(unsigned char c:s) {result+=digits[c>>4];result+=digits[c&15];}
    return result;
}
std::string unhex(const std::string &s)
{
    if(s.size()%2) return "";
    std::string result;
    for(size_t i=0;i<s.size();i+=2) {
        unsigned value=0;
        for(size_t j=i;j<i+2;j++) {
            char c=s[j];if(c>='0'&&c<='9') value=value*16+c-'0';
            else if(c>='a'&&c<='f') value=value*16+c-'a'+10;else return "";
        }
        if(!value) return "";
        result+=(char)value;
    }
    return result;
}
bool read_bytes(const std::string &path,std::string &bytes)
{
    FILE *file=fopen(path.c_str(),"rb");if(!file) return false;
    char buffer[4096];size_t count;bytes.clear();
    while((count=fread(buffer,1,sizeof(buffer),file))!=0) {
        bytes.append(buffer,count);if(bytes.size()>65536) {fclose(file);return false;}
    }
    bool good=!ferror(file);fclose(file);return good;
}
bool atomic_bytes(const std::string &path,const std::string &bytes)
{
    std::string temporary;
    HANDLE file=INVALID_HANDLE_VALUE;
    for(unsigned i=0;i<100 && file==INVALID_HANDLE_VALUE;i++) {
        char suffix[96];sprintf(suffix,".new-%lu-%llu-%u",GetCurrentProcessId(),GetTickCount64(),i);
        temporary=path+suffix;
        file=CreateFileA(temporary.c_str(),GENERIC_WRITE,0,nullptr,CREATE_NEW,FILE_ATTRIBUTE_NORMAL,nullptr);
        if(file==INVALID_HANDLE_VALUE && GetLastError()!=ERROR_FILE_EXISTS) return false;
    }
    if(file==INVALID_HANDLE_VALUE) return false;
    DWORD written=0;
    bool good=WriteFile(file,bytes.data(),(DWORD)bytes.size(),&written,nullptr)!=FALSE && written==bytes.size();
    if(good) good=FlushFileBuffers(file)!=FALSE;
    if(!CloseHandle(file)) good=false;
    if(good) good=MoveFileExA(temporary.c_str(),path.c_str(),MOVEFILE_REPLACE_EXISTING|MOVEFILE_WRITE_THROUGH)!=FALSE;
    if(!good) DeleteFileA(temporary.c_str());
    return good;
}
bool field_valid(const std::string &s)
{
    if(s.size()>4096) return false;
    for(unsigned char c:s) if(c<32 || c==127) return false;
    return true;
}
bool remote_location(const std::string &s,bool publishing)
{
    if(s.empty()) return true;
    size_t start=s.find("://");if(start==std::string::npos) return false;
    std::string scheme=s.substr(0,start);
    if(publishing) {
        if(_stricmp(scheme.c_str(),"http") && _stricmp(scheme.c_str(),"ftp")) return false;
    } else if(_stricmp(scheme.c_str(),"http") && _stricmp(scheme.c_str(),"https")) return false;
    size_t end=s.find_first_of("/?#",start+3);
    std::string host=s.substr(start+3,end==std::string::npos?std::string::npos:end-start-3);
    return !host.empty() && host.find('@')==std::string::npos && host.find_first_of(" \\\t") == std::string::npos;
}
bool executable_path(const std::string &s)
{
    if(s.empty()) return true;
    DWORD attributes=GetFileAttributesA(s.c_str());
    const char *extension=PathFindExtensionA(s.c_str());
    return attributes!=INVALID_FILE_ATTRIBUTES && !(attributes&FILE_ATTRIBUTE_DIRECTORY)
        && (!_stricmp(extension,".exe") || !_stricmp(extension,".com"));
}
std::string local_template(const std::string &s)
{
    if(s.empty()) return "";
    if(!_strnicmp(s.c_str(),"file:",5)) {
        char path[32768];DWORD size=sizeof(path);
        if(FAILED(PathCreateFromUrlA(s.c_str(),path,&size,0))) return "";
        return path;
    }
    if(s.find("://")!=std::string::npos) return "";
    return s;
}
