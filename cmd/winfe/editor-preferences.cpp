void WFE_EditorApplyPreferences(MWContext *context,bool new_document)
{
    if(!context || !EDT_HaveEditBuffer(context)) return;
    EditorPreferences value=WFE_EditorPreferencesRead();
    EDT_SetAutoSavePeriod(context,value.autosave_minutes);
    /* keep_images and maintain_links are arguments to save/image operations;
     * EDT_PageData does not retain either preference. Setting page data here
     * would create an unrelated undo command and relayout the document. */
    if(new_document && !value.author.empty()) {
        EDT_MetaData *meta=EDT_NewMetaData();
        if(meta) {meta->bHttpEquiv=FALSE;meta->pName=XP_STRDUP("Author");meta->pContent=XP_STRDUP(value.author.c_str());EDT_SetMetaData(context,meta);EDT_FreeMetaData(meta);}
    }
}
std::string WFE_EditorQuoteArgument(const std::string &argument)
{
    std::string result="\"";size_t slashes=0;
    for(char c:argument) {
        if(c=='\\') {slashes++;continue;}
        if(c=='\"') result.append(slashes*2+1,'\\');else result.append(slashes,'\\');
        slashes=0;result+=c;
    }
    result.append(slashes*2,'\\');return result+"\"";
}

/* The runtime fixture restores the exact original profile bytes, including an
 * absent file. No user preference values are left behind by the smoke test. */
