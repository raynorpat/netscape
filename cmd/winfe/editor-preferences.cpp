    EditorPreferences loaded=WFE_EditorPreferencesRead();
    stored=stored && loaded.author==fixture.author && loaded.autosave_minutes==7 && !loaded.maintain_links && !loaded.keep_images
        && loaded.publish_location==fixture.publish_location && loaded.browse_location==fixture.browse_location && loaded.publish_username==fixture.publish_username;
    std::string capture=std::string(report)+".preferences";
    PreferenceSheet dialog(CWnd::FromHandle(WFE_DocumentWindow(context)),true,capture.c_str());
